// Golden generator for the Analyze post export of src-tauri/crates/
// pipette-hub: `prepareAnalyticsExport` (hub-ipc-analytics-prepare.ts)
// and the preview values of hub-ipc-analytics.ts, run on the real
// better-sqlite3 over the seed of cases.ts, in the Hub fixture harness
// (fixed clock and machine hash), in UTC.
//
// - tests/fixtures/ts_hub_analytics_export_seed.jsonl — the seed the cache
//   holds.
// - tests/fixtures/ts_hub_analytics_export.json — the userData tree, and per
//   case the parameters and what the preparation gave: the export as the
//   exact text JSON.stringify writes with the preview values, the failure
//   with its totals, or the message it threw.
//
// Run: pnpm run generate:hub-fixtures

import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { writeFixture, writeJsonFixture } from '../../fixture-files'
import { FIXED_NOW, seedUserData } from '../../sync-fixtures/harness'
import { FIXED_MACHINE_HASH, settledTree } from '../hub-harness'
import { hubFixturePath } from '../paths'
import { EXPORT_CASES, buildExportSeed, exportTree, type ExportCase } from './cases'
import { TypingAnalyticsDB, setTypingAnalyticsDBForTests } from '../../../src/main/typing-analytics/db/typing-analytics-db'
import { applyRowsToCache } from '../../../src/main/typing-analytics/jsonl/apply-to-cache'
import { readRows } from '../../../src/main/typing-analytics/jsonl/jsonl-reader'
import { prepareAnalyticsExport } from '../../../src/main/hub/hub-ipc-analytics-prepare'
import { estimateAnalyticsExportSizeBytes, validateAnalyticsExport } from '../../../src/main/hub/hub-analytics'

const SEED_PATH = hubFixturePath('ts_hub_analytics_export_seed.jsonl')
const FIXTURE_PATH = hubFixturePath('ts_hub_analytics_export.json')

let dbDir = ''
let db: TypingAnalyticsDB | null = null

async function run(c: ExportCase): Promise<Record<string, unknown>> {
  let built: Awaited<ReturnType<typeof prepareAnalyticsExport>>
  try {
    built = await prepareAnalyticsExport(c.params as unknown as Parameters<typeof prepareAnalyticsExport>[0])
  } catch (err) {
    if (!(err instanceof Error)) throw err
    return { name: c.name, params: c.params, thrown: err.message }
  }
  if (!built.ok) {
    return {
      name: c.name,
      params: c.params,
      failed: { error: built.error, totalKeystrokes: built.totalKeystrokes, rangeMs: built.rangeMs },
    }
  }
  const { exportData } = built
  return {
    name: c.name,
    params: c.params,
    exportJson: JSON.stringify(exportData),
    preview: {
      totalKeystrokes: exportData.snapshot.totalKeystrokes,
      rangeMs: exportData.snapshot.range.toMs - exportData.snapshot.range.fromMs,
      estimatedBytes: estimateAnalyticsExportSizeBytes(exportData),
      validation: validateAnalyticsExport(exportData),
    },
  }
}

describe('hub analytics export fixtures', () => {
  beforeAll(async () => {
    writeFixture(SEED_PATH, buildExportSeed())
    dbDir = mkdtempSync(join(tmpdir(), 'pipette-hub-analytics-export-'))
    db = new TypingAnalyticsDB(join(dbDir, 'cache.db'))
    applyRowsToCache(db, (await readRows(SEED_PATH)).rows)
    setTypingAnalyticsDBForTests(db)
  })

  afterAll(() => {
    db?.close()
    if (dbDir) rmSync(dbDir, { recursive: true, force: true })
  })

  it('records the export of each case', async () => {
    expect(process.env.TZ).toBe('UTC')
    const tree = exportTree()
    const dir = seedUserData(tree)
    const before = await settledTree(dir)
    const cases = []
    for (const c of EXPORT_CASES) cases.push(await run(c))
    // The same case gives the same record on a second run, and the
    // preparation writes nothing.
    expect(await run(EXPORT_CASES[0])).toEqual(cases[0])
    expect(await settledTree(dir)).toEqual(before)
    expect(cases.filter((c) => 'exportJson' in c).length).toBeGreaterThan(20)
    writeJsonFixture(FIXTURE_PATH, {
      about: 'The Electron preparation of the Analyze post export (prepareAnalyticsExport, hub-ipc-analytics-prepare.ts) per case of scripts/hub-fixtures/analytics-export/cases.ts, on the seed ts_hub_analytics_export_seed.jsonl and the userData tree below (with the fixed installation id), at nowMs, with ownHash as this device, in the time zone timeZone: the export as the text JSON.stringify writes with the preview values of hub-ipc-analytics.ts, the failure, or the message it threw. Generated by scripts/hub-fixtures/analytics-export/record-analytics-export.test.ts; do not edit.',
      nowMs: FIXED_NOW,
      ownHash: FIXED_MACHINE_HASH,
      timeZone: 'UTC',
      tree,
      cases,
    })
  })
})
