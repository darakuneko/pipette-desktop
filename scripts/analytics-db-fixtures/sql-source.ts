// The Rust source of the SQL constants the crate includes (data/sql.rs):
// every string the TypeScript DB layer prepares, collected through a fake
// connection whose `prepare` returns its argument. A constant is named
// after its statement key (`selectLayerUsageForUidStmt` →
// `SELECT_LAYER_USAGE_FOR_UID`); the n-gram statements, prepared once per
// table, are prefixed with the table (`BIGRAM_MERGE`, `TRIGRAM_MERGE`).
//
// Not collected, so hand-written in the crate's src/schema.rs: the migration
// SQL, which typing-analytics-db-base.ts runs inline with `exec`.

import type { Database as DatabaseType } from 'better-sqlite3'
import { CREATE_META_SQL, CREATE_SCHEMA_SQL } from '../../src/main/typing-analytics/db/schema'
import { prepareIngestStatements } from '../../src/main/typing-analytics/db/sql/ingest-statements'
import { prepareMergeStatements } from '../../src/main/typing-analytics/db/sql/merge-statements'
import { prepareMetaStatements } from '../../src/main/typing-analytics/db/sql/meta-statements'
import { BIGRAM_OVERLAP_EXTRA_COLUMNS, prepareNgramStatements } from '../../src/main/typing-analytics/db/sql/ngram-statements'
import { prepareRangeStatements } from '../../src/main/typing-analytics/db/sql/range-query-statements'
import { prepareSummaryStatements } from '../../src/main/typing-analytics/db/sql/summary-query-statements'
import { prepareSyncStatements } from '../../src/main/typing-analytics/db/sql/sync-statements'

interface SqlConstant {
  name: string
  doc: string
  text: string
}

type Prepare = (db: DatabaseType) => object

/** `fooBarStmt` → `FOO_BAR`. */
function constantName(key: string): string {
  return key.replace(/Stmt$/, '').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()
}

function collectSql(): SqlConstant[] {
  const fake = { prepare: (sql: string): string => sql } as unknown as DatabaseType
  const groups: Array<{ prepare: Prepare; fn: string; file: string; prefix?: string; table?: string }> = [
    { prepare: prepareMetaStatements, fn: 'prepareMetaStatements', file: 'meta-statements.ts' },
    { prepare: prepareIngestStatements, fn: 'prepareIngestStatements', file: 'ingest-statements.ts' },
    { prepare: prepareMergeStatements, fn: 'prepareMergeStatements', file: 'merge-statements.ts' },
    { prepare: prepareSyncStatements, fn: 'prepareSyncStatements', file: 'sync-statements.ts' },
    { prepare: prepareSummaryStatements, fn: 'prepareSummaryStatements', file: 'summary-query-statements.ts' },
    { prepare: prepareRangeStatements, fn: 'prepareRangeStatements', file: 'range-query-statements.ts' },
    {
      prepare: (db) => prepareNgramStatements(db, 'typing_bigram_minute', 'bigram_id', BIGRAM_OVERLAP_EXTRA_COLUMNS),
      fn: 'prepareNgramStatements', file: 'ngram-statements.ts', prefix: 'BIGRAM_', table: 'typing_bigram_minute',
    },
    {
      prepare: (db) => prepareNgramStatements(db, 'typing_trigram_minute', 'trigram_id', []),
      fn: 'prepareNgramStatements', file: 'ngram-statements.ts', prefix: 'TRIGRAM_', table: 'typing_trigram_minute',
    },
  ]
  const statements = groups.flatMap(({ prepare, fn, file, prefix = '', table }) =>
    Object.entries(prepare(fake) as Record<string, string>).map(([key, text]) => ({
      name: prefix + constantName(key),
      doc: `\`${key}\` of \`${fn}\`${table ? ` for ${table}` : ''} (${file}).`,
      text,
    })))
  return [
    { name: 'CREATE_META', doc: 'The meta table and connection PRAGMAs (`CREATE_META_SQL`, schema.ts). Runs before any migration.', text: CREATE_META_SQL },
    { name: 'CREATE_SCHEMA', doc: 'Every data table and index (`CREATE_SCHEMA_SQL`, schema.ts). Runs after the migrations.', text: CREATE_SCHEMA_SQL },
    ...statements,
  ]
}

/** The text of data/sql.rs. Each string becomes a raw string literal, so
 * the SQL reads the same in both languages. */
export function buildSqlSource(): string {
  const constants = collectSql()
  const names = new Set(constants.map((c) => c.name))
  if (names.size !== constants.length) throw new Error('two statements share a constant name')
  const items = constants.map(({ name, doc, text }) => {
    if (typeof text !== 'string') throw new Error(`${name}: no SQL text collected`)
    if (text.includes('"#')) throw new Error(`${name}: contains "# and cannot be a r#"…"# literal`)
    return `/// ${doc}\npub const ${name}: &str = r#"${text}"#;`
  })
  return `// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/analytics-db-fixtures/record-analytics-db-fixtures.test.ts
// (pnpm run generate:analytics-db-fixtures). Do not edit by hand.
//
// The SQL text of src/main/typing-analytics/db/, character for character.
// Included by src/sql.rs.

${items.join('\n\n')}
`
}
