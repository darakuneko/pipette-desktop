// The Rust source of the keycode tables the Layout Comparison resolver of
// src-tauri/crates/pipette-typing-analytics reads (data/keycodes.rs), from
// the keycode registry as the Electron main process holds it: the module
// state src/shared/keycodes/keycodes.ts builds when it loads, which the
// main process never rebuilds for a connected keyboard.
//
// - MASKED_KEYCODES — `maskedKeycodes`: the operators whose `OP(inner)`
//   form `findInnerKeycode` unwraps.
// - KEYCODES — `KEYCODES_MAP` as `(key, qmkId)`: what `findKeycode` finds
//   for a key, by the qmkId of the keycode it finds.
// - PRINTABLE_KEYCODES — the keycodes of `qmkIdToKeycode` with a printable
//   character, in the map's order: the QWERTY base of
//   src/shared/keymap/layout-parse.ts.

import { KEYCODES_MAP, maskedKeycodes, qmkIdToKeycode } from '../../src/shared/keycodes/keycodes'

/** A Rust string literal: JSON's escapes are Rust's, but for `\\u`. */
function rustString(text: string): string {
  const literal = JSON.stringify(text)
  if (literal.includes('\\u')) throw new Error(`${literal} needs a \\u escape`)
  return literal
}

function pairs(entries: Array<[string, string]>): string {
  return entries.map(([a, b]) => `    (${rustString(a)}, ${rustString(b)}),`).join('\n')
}

/** The text of data/keycodes.rs. */
export function buildKeycodeSource(): string {
  const masked = [...maskedKeycodes].map((id) => `    ${rustString(id)},`).join('\n')
  const keycodes = [...KEYCODES_MAP].map(([key, keycode]): [string, string] => [key, keycode.qmkId])
  const printable = [...qmkIdToKeycode.values()]
    .filter((keycode) => keycode.printable !== undefined)
    .map((keycode): [string, string] => [keycode.qmkId, keycode.printable as string])
  return `// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/analytics-db-fixtures/record-analytics-query-fixtures.test.ts
// (pnpm run generate:analytics-db-fixtures). Do not edit by hand.
//
// The keycode registry of src/shared/keycodes/keycodes.ts as the Electron
// main process holds it. Included by src/layout_resolver/keycodes.rs.

/// \`maskedKeycodes\`.
pub const MASKED_KEYCODES: &[&str] = &[
${masked}
];

/// \`KEYCODES_MAP\`: (key, qmkId of the keycode).
pub const KEYCODES: &[(&str, &str)] = &[
${pairs(keycodes)}
];

/// The keycodes with a printable character, in \`qmkIdToKeycode\` order:
/// (qmkId, character).
pub const PRINTABLE_KEYCODES: &[(&str, &str)] = &[
${pairs(printable)}
];
`
}
